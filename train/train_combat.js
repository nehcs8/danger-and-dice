// DQN training loop for the combat policy.
// Run from the project root: node train/train_combat.js
//
// Outputs: js/data/weights/combat_weights.js (overwritten every SAVE_EVERY episodes)
//
// Usage:
//   node train/train_combat.js            # full training run
//   node train/train_combat.js --fast     # 1000 episodes for quick smoke-test

'use strict';

const fs   = require('fs');
const path = require('path');
const { TinyNN }    = require('./nn.js');
const { CombatEnv, STATE_DIM, ACTION_DIM, ACTION_NAMES } = require('./combat_env.js');

// ── Hyperparameters ───────────────────────────────────────────────────────────
const FAST_MODE     = process.argv.includes('--fast');
const EPISODES      = FAST_MODE ? 1_000  : 20_000;
const BUFFER_SIZE   = 10_000;
const BATCH_SIZE    = 32;
const GAMMA         = 0.95;
const LR            = 0.001;
const EPS_START     = 1.0;
const EPS_END       = 0.05;
const EPS_DECAY     = EPISODES * 0.6;  // steps to decay epsilon over
const TARGET_UPDATE = 200;             // copy online → target every N steps
const SAVE_EVERY    = FAST_MODE ? 200  : 2_000;
const LOG_EVERY     = FAST_MODE ? 100  : 1_000;
const HIDDEN        = 32;

// ── Setup ─────────────────────────────────────────────────────────────────────
const online  = new TinyNN([STATE_DIM, HIDDEN, ACTION_DIM]);
const target  = online.clone();
const env     = new CombatEnv();
const buffer  = []; // circular replay buffer: { obs, action, reward, nextObs, done, mask }

let totalSteps = 0;
let epsilon    = EPS_START;

// ── Replay buffer ─────────────────────────────────────────────────────────────
function pushTransition(t) {
  if (buffer.length >= BUFFER_SIZE) buffer.shift();
  buffer.push(t);
}

function sampleBatch() {
  const out = [];
  for (let i = 0; i < BATCH_SIZE; i++) {
    out.push(buffer[Math.floor(Math.random() * buffer.length)]);
  }
  return out;
}

// ── Epsilon-greedy action selection ──────────────────────────────────────────
function chooseAction(obs, mask) {
  epsilon = Math.max(EPS_END, EPS_START - (EPS_START - EPS_END) * (totalSteps / EPS_DECAY));
  if (Math.random() < epsilon) {
    // Random valid action
    const valid = mask.map((ok, i) => ok ? i : -1).filter(i => i >= 0);
    return valid[Math.floor(Math.random() * valid.length)];
  }
  const q = online.forward(obs);
  // Mask invalid actions with -Infinity before argmax
  let best = -1, bestQ = -Infinity;
  for (let a = 0; a < ACTION_DIM; a++) {
    if (mask[a] && q[a] > bestQ) { bestQ = q[a]; best = a; }
  }
  return best;
}

// ── DQN update ────────────────────────────────────────────────────────────────
function trainStep() {
  if (buffer.length < BATCH_SIZE) return;
  const batch = sampleBatch();
  for (const { obs, action, reward, nextObs, done, nextMask } of batch) {
    let targetQ;
    if (done) {
      targetQ = reward;
    } else {
      const qNext = target.forward(nextObs);
      // Double DQN: pick action with online net, evaluate with target net
      const qNextOnline = online.forward(nextObs);
      let bestA = -1, bestQO = -Infinity;
      for (let a = 0; a < ACTION_DIM; a++) {
        if (nextMask[a] && qNextOnline[a] > bestQO) { bestQO = qNextOnline[a]; bestA = a; }
      }
      targetQ = reward + GAMMA * (bestA >= 0 ? qNext[bestA] : 0);
    }
    online.forward(obs); // populate cache for backward
    online.update(action, targetQ, LR);
  }
}

// ── Curriculum: ramp mob tier as training progresses ─────────────────────────
const TIER_THRESHOLDS = [0.25, 0.50, 0.75, 1.0];
let   _lastTier = 0;

function getTier(episode) {
  const frac = episode / EPISODES;
  let tier = 0;
  if (frac >= 0.75) tier = 3;
  else if (frac >= 0.50) tier = 2;
  else if (frac >= 0.25) tier = 1;
  return tier;
}

// Returns true if we just crossed into a new tier this episode
function tierJustChanged(tier) {
  if (tier !== _lastTier) { _lastTier = tier; return true; }
  return false;
}

// ── Weights export ────────────────────────────────────────────────────────────
const WEIGHTS_PATH = path.join(__dirname, '..', 'js', 'data', 'weights', 'combat_weights.js');

function saveWeights(episode) {
  fs.mkdirSync(path.dirname(WEIGHTS_PATH), { recursive: true });
  const data = JSON.stringify(online.serialize());
  const js   = `// Auto-generated by train/train_combat.js — episode ${episode}\n`
             + `// Do not edit by hand. Re-run training to update.\n`
             + `const COMBAT_WEIGHTS = ${data};\n`;
  fs.writeFileSync(WEIGHTS_PATH, js);
  console.log(`  → weights saved (episode ${episode})`);
}

// ── Training loop ─────────────────────────────────────────────────────────────
console.log(`Training combat policy — ${EPISODES} episodes, hidden=${HIDDEN}, buffer=${BUFFER_SIZE}`);
if (FAST_MODE) console.log('  (fast mode)');

let rewardHistory = [];
let winHistory    = [];

for (let ep = 0; ep < EPISODES; ep++) {
  const tier = getTier(ep);
  // Reset exploration when entering a new tier so the policy can adapt
  if (tierJustChanged(tier) && tier > 0) {
    epsilon = Math.min(EPS_START, epsilon + 0.4);
    console.log(`  [tier ${tier} started — epsilon reset to ${epsilon.toFixed(2)}]`);
  }
  let { obs, done } = env.reset(tier);
  let epReward = 0;
  let won      = false;

  while (!done) {
    const mask   = env.getActionMask();
    const action = chooseAction(obs, mask);
    const { obs: nextObs, reward, done: d } = env.step(action);
    const nextMask = env.getActionMask();

    pushTransition({ obs, action, reward, nextObs, done: d, nextMask });
    trainStep();

    obs      = nextObs;
    done     = d;
    epReward += reward;
    totalSteps++;

    if (totalSteps % TARGET_UPDATE === 0) {
      // Copy online weights to target network
      const data = online.serialize();
      target.layers = data.map(l => ({ w: l.w.slice(), b: l.b.slice(), inD: l.inD, outD: l.outD }));
    }
  }

  // Determine win: env._totalReward > 0 is a rough proxy; check last reward
  won = env._totalReward > 15;
  rewardHistory.push(epReward);
  winHistory.push(won ? 1 : 0);

  if ((ep + 1) % SAVE_EVERY === 0) saveWeights(ep + 1);

  if ((ep + 1) % LOG_EVERY === 0) {
    const recentR = rewardHistory.slice(-LOG_EVERY);
    const recentW = winHistory.slice(-LOG_EVERY);
    const avgR = (recentR.reduce((a, b) => a + b, 0) / recentR.length).toFixed(1);
    const winP = ((recentW.reduce((a, b) => a + b, 0) / recentW.length) * 100).toFixed(0);
    console.log(`ep ${String(ep + 1).padStart(6)} | tier ${tier} | eps ${epsilon.toFixed(3)} | avgR ${avgR} | win% ${winP}%`);
  }
}

saveWeights(EPISODES);
console.log('Training complete.');
